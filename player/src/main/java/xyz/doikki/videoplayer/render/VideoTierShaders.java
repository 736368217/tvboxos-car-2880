package xyz.doikki.videoplayer.render;

/**
 * 多档位视效 shader —— 严格按《TVBoxOS 车载高阶视效引擎方案 v2.0》实现。
 *
 * 文档原文是 GLSL ES 3.00（#version 300 es / in-out / texture），本工程渲染器是 GLES2，
 * 这里只做语法等价改写（varying / gl_FragColor / texture2D），算法、核函数、钳制逻辑保持原样。
 *
 *  - SR2：FSR_EASU_Pass1 + FSR_RCAS_Pass2（两个独立 Pass，文档 §3.1）
 *  - MEMC2：TemporalCubic4Tap（文档 §4.1）
 *  - MEMC3：SafeFlowEstimate_480p + SafeFlowWarpWithCubicFallback（文档 §4.2）
 *  - SR1：保持原 SGSR1 基线（沿用 VideoShaders.OUTPUT_FRAGMENT）
 */
public final class VideoTierShaders {

    private VideoTierShaders() {
    }

    private static final String HEADER =
            "#ifdef GL_FRAGMENT_PRECISION_HIGH\nprecision highp float;\n#else\nprecision mediump float;\n#endif\n"
                    + "varying highp vec2 vTexCoord;\n";

    // ---------------------------------------------------------------- MEMC

    /** 4 帧 Catmull-Rom 三次时域卷积（文档 §4.1 原样）。 */
    public static final String TEMPORAL_CUBIC = HEADER
            + "uniform sampler2D uFrameMinus1;\n"
            + "uniform sampler2D uFrame0;\n"
            + "uniform sampler2D uFrame1;\n"
            + "uniform sampler2D uFrame2;\n"
            + "uniform float uAlpha;\n"
            + "uniform float uMitchellB;\n"
            + "float cubicWeight(float x, float B, float C) {\n"
            + "  float ax = abs(x);\n"
            + "  if (ax < 1.0) {\n"
            + "    return ((12.0 - 9.0*B - 6.0*C)*ax*ax*ax + (-18.0 + 12.0*B + 6.0*C)*ax*ax + (6.0 - 2.0*B))/6.0;\n"
            + "  } else if (ax < 2.0) {\n"
            + "    return ((-B - 6.0*C)*ax*ax*ax + (6.0*B + 30.0*C)*ax*ax + (-12.0*B - 48.0*C)*ax + (8.0*B + 24.0*C))/6.0;\n"
            + "  }\n"
            + "  return 0.0;\n"
            + "}\n"
            + "void main() {\n"
            + "  vec4 c0 = texture2D(uFrame0, vTexCoord);\n"
            + "  if (uAlpha <= 0.01) { gl_FragColor = c0; return; }\n"
            + "  vec4 c1 = texture2D(uFrame1, vTexCoord);\n"
            + "  if (uAlpha >= 0.99) { gl_FragColor = c1; return; }\n"
            + "  float diff01 = dot(abs(c1.rgb - c0.rgb), vec3(0.299,0.587,0.114));\n"
            + "  if (diff01 > 0.32) { gl_FragColor = (uAlpha < 0.5) ? c0 : c1; return; }\n"
            + "  vec4 cm1 = texture2D(uFrameMinus1, vTexCoord);\n"
            + "  vec4 c2  = texture2D(uFrame2, vTexCoord);\n"
            + "  float B = uMitchellB;\n"
            + "  float C = 0.5 * (1.0 - B);\n"
            + "  float wm1 = cubicWeight(1.0 + uAlpha, B, C);\n"
            + "  float w0  = cubicWeight(uAlpha,       B, C);\n"
            + "  float w1  = cubicWeight(1.0 - uAlpha, B, C);\n"
            + "  float w2  = cubicWeight(2.0 - uAlpha, B, C);\n"
            + "  float wSum = wm1 + w0 + w1 + w2;\n"
            + "  vec4 interp = (cm1*wm1 + c0*w0 + c1*w1 + c2*w2) / wSum;\n"
            + "  vec4 minBound = min(c0, c1) - vec4(0.015);\n"
            + "  vec4 maxBound = max(c0, c1) + vec4(0.015);\n"
            + "  gl_FragColor = clamp(interp, max(minBound, vec4(0.0)), min(maxBound, vec4(1.0)));\n"
            + "}\n";

    /** Safe-Flow Pass 1：480p 块匹配 + 结构张量光流（文档 §4.2 原样）。 */
    public static final String SAFE_FLOW_ESTIMATE = HEADER
            + "uniform sampler2D uPrevLuma480p;\n"
            + "uniform sampler2D uCurrLuma480p;\n"
            + "uniform vec2 uInvSize480p;\n"
            + "float getL(sampler2D t, vec2 uv) { return texture2D(t, clamp(uv, vec2(0.001), vec2(0.999))).r; }\n"
            + "float patchSAD(vec2 uv0, vec2 uv1) {\n"
            + "  float sad = 0.0;\n"
            + "  for (int y = -1; y <= 1; y++) {\n"
            + "    for (int x = -1; x <= 1; x++) {\n"
            + "      vec2 off = vec2(float(x), float(y)) * uInvSize480p;\n"
            + "      sad += abs(getL(uCurrLuma480p, uv1 + off) - getL(uPrevLuma480p, uv0 + off));\n"
            + "    }\n"
            + "  }\n"
            + "  return sad;\n"
            + "}\n"
            + "void main() {\n"
            + "  float zeroSad = patchSAD(vTexCoord, vTexCoord);\n"
            + "  if (zeroSad < 0.018) { gl_FragColor = vec4(0.0,0.0,1.0,0.0); return; }\n"
            + "  vec2 bestVec = vec2(0.0);\n"
            + "  float minSad = zeroSad * 0.90;\n"
            + "  for (int i = 0; i < 8; i++) {\n"
            + "    vec2 d = vec2(0.0);\n"
            + "    if (i==0) d=vec2(-2.0,0.0); else if (i==1) d=vec2(2.0,0.0);\n"
            + "    else if (i==2) d=vec2(0.0,-2.0); else if (i==3) d=vec2(0.0,2.0);\n"
            + "    else if (i==4) d=vec2(-1.0,-1.0); else if (i==5) d=vec2(1.0,-1.0);\n"
            + "    else if (i==6) d=vec2(-1.0,1.0); else d=vec2(1.0,1.0);\n"
            + "    vec2 cand = d * uInvSize480p;\n"
            + "    float sad = patchSAD(vTexCoord - 0.5*cand, vTexCoord + 0.5*cand);\n"
            + "    if (sad < minSad) { minSad = sad; bestVec = cand; }\n"
            + "  }\n"
            + "  float sumIx2 = 0.005, sumIy2 = 0.005, sumIxy = 0.0, sumIxt = 0.0, sumIyt = 0.0;\n"
            + "  for (int dy = -1; dy <= 1; dy++) {\n"
            + "    for (int dx = -1; dx <= 1; dx++) {\n"
            + "      vec2 off = vec2(float(dx), float(dy)) * uInvSize480p;\n"
            + "      vec2 uv0 = vTexCoord - 0.5*bestVec + off;\n"
            + "      vec2 uv1 = vTexCoord + 0.5*bestVec + off;\n"
            + "      float Ix = 0.5*((getL(uPrevLuma480p, uv0 + vec2(uInvSize480p.x,0.0)) - getL(uPrevLuma480p, uv0 - vec2(uInvSize480p.x,0.0)))"
            + "                    + (getL(uCurrLuma480p, uv1 + vec2(uInvSize480p.x,0.0)) - getL(uCurrLuma480p, uv1 - vec2(uInvSize480p.x,0.0))));\n"
            + "      float Iy = 0.5*((getL(uPrevLuma480p, uv0 + vec2(0.0,uInvSize480p.y)) - getL(uPrevLuma480p, uv0 - vec2(0.0,uInvSize480p.y)))"
            + "                    + (getL(uCurrLuma480p, uv1 + vec2(0.0,uInvSize480p.y)) - getL(uCurrLuma480p, uv1 - vec2(0.0,uInvSize480p.y))));\n"
            + "      float It = getL(uCurrLuma480p, uv1) - getL(uPrevLuma480p, uv0);\n"
            + "      sumIx2 += Ix*Ix; sumIy2 += Iy*Iy; sumIxy += Ix*Iy; sumIxt += Ix*It; sumIyt += Iy*It;\n"
            + "    }\n"
            + "  }\n"
            + "  float det = max(sumIx2*sumIy2 - sumIxy*sumIxy, 1e-6);\n"
            + "  vec2 subPx = clamp(vec2(-(sumIy2*sumIxt - sumIxy*sumIyt)/det, -(sumIx2*sumIyt - sumIxy*sumIxt)/det), vec2(-1.5), vec2(1.5));\n"
            + "  vec2 finalFlowUv = bestVec + subPx * uInvSize480p;\n"
            + "  float conf = smoothstep(0.25, 0.03, minSad / 9.0);\n"
            + "  gl_FragColor = vec4(finalFlowUv, conf, 1.0);\n"
            + "}\n";

    /** Safe-Flow Pass 2：三重防伪影锁 + 回退 4 帧卷积（文档 §4.2 原样）。 */
    public static final String SAFE_FLOW_WARP = HEADER
            + "uniform sampler2D uFrameMinus1;\n"
            + "uniform sampler2D uFrame0;\n"
            + "uniform sampler2D uFrame1;\n"
            + "uniform sampler2D uFrame2;\n"
            + "uniform sampler2D uFlowTex480p;\n"
            + "uniform vec2 uFlowInvSize;\n"
            + "uniform float uAlpha;\n"
            + "vec4 computeSafeCubicFallback(vec2 uv, vec4 c0, vec4 c1) {\n"
            + "  vec4 cm1 = texture2D(uFrameMinus1, uv);\n"
            + "  vec4 c2  = texture2D(uFrame2, uv);\n"
            + "  float a = uAlpha; float a2 = a*a; float a3 = a2*a;\n"
            + "  float wm1 = -0.5*a + a2 - 0.5*a3;\n"
            + "  float w0  =  1.0 - 2.5*a2 + 1.5*a3;\n"
            + "  float w1  =  0.5*a + 2.0*a2 - 1.5*a3;\n"
            + "  float w2  = -0.5*a2 + 0.5*a3;\n"
            + "  vec4 res = cm1*wm1 + c0*w0 + c1*w1 + c2*w2;\n"
            + "  return clamp(res, min(c0,c1) - vec4(0.01), max(c0,c1) + vec4(0.01));\n"
            + "}\n"
            + "void main() {\n"
            + "  vec4 c0 = texture2D(uFrame0, vTexCoord);\n"
            + "  if (uAlpha <= 0.01) { gl_FragColor = c0; return; }\n"
            + "  vec4 c1 = texture2D(uFrame1, vTexCoord);\n"
            + "  if (uAlpha >= 0.99) { gl_FragColor = c1; return; }\n"
            + "  vec3 fc = texture2D(uFlowTex480p, vTexCoord).xyz;\n"
            + "  vec2 fL = texture2D(uFlowTex480p, vTexCoord - vec2(uFlowInvSize.x,0.0)).xy;\n"
            + "  vec2 fR = texture2D(uFlowTex480p, vTexCoord + vec2(uFlowInvSize.x,0.0)).xy;\n"
            + "  vec2 fU = texture2D(uFlowTex480p, vTexCoord - vec2(0.0,uFlowInvSize.y)).xy;\n"
            + "  vec2 fD = texture2D(uFlowTex480p, vTexCoord + vec2(0.0,uFlowInvSize.y)).xy;\n"
            + "  vec2 minF = min(min(fL,fR), min(fU,fD));\n"
            + "  vec2 maxF = max(max(fL,fR), max(fU,fD));\n"
            + "  vec2 clampedF = clamp(fc.xy, minF, maxF);\n"
            + "  vec2 flow = 0.40*clampedF + 0.15*(fL+fR+fU+fD);\n"
            + "  vec2 uv0 = clamp(vTexCoord - uAlpha*flow, vec2(0.001), vec2(0.999));\n"
            + "  vec2 uv1 = clamp(vTexCoord + (1.0-uAlpha)*flow, vec2(0.001), vec2(0.999));\n"
            + "  vec4 w0 = texture2D(uFrame0, uv0);\n"
            + "  vec4 w1 = texture2D(uFrame1, uv1);\n"
            + "  vec4 flowInterp = mix(w0, w1, uAlpha);\n"
            + "  float warpError = dot(abs(w0.rgb - w1.rgb), vec3(0.299,0.587,0.114));\n"
            + "  float occlusionTrust = fc.z * smoothstep(0.12, 0.025, warpError);\n"
            + "  float subtitleSafeMask = (vTexCoord.y > 0.84) ? 0.25 : 1.0;\n"
            + "  float finalFlowWeight = occlusionTrust * subtitleSafeMask;\n"
            + "  vec4 cubicFallback = computeSafeCubicFallback(vTexCoord, c0, c1);\n"
            + "  gl_FragColor = mix(cubicFallback, flowInterp, finalFlowWeight);\n"
            + "}\n";

    /** SR2 Pass1：FSR EASU（文档 §3.1 原样）。 */
    public static final String FSR_EASU = HEADER
            + "uniform sampler2D uInputTex;\n"
            + "uniform vec4 uSrcSize;\n"
            + "float APrxLoRcpF1(float a) { return uintBitsToFloat(0x7ef07ebbu - floatBitsToUint(max(a, 1e-6))); }\n"
            + "float APrxLoRsqF1(float a) { return uintBitsToFloat(0x5f347d74u - (floatBitsToUint(max(a, 1e-6)) >> 1u)); }\n"
            + "float getLuma(vec3 rgb) { return dot(rgb, vec3(0.2126,0.7152,0.0722)); }\n"
            + "void FsrEasuTap(inout vec3 aC, inout float aW, vec2 off, vec2 dir, vec2 len, float lob, float clp, vec3 c) {\n"
            + "  vec2 v; v.x = (off.x*dir.x) + (off.y*dir.y); v.y = (off.x*(-dir.y)) + (off.y*dir.x);\n"
            + "  v *= len;\n"
            + "  float d2 = min(dot(v,v), clp);\n"
            + "  float wB = (2.0/5.0)*d2 - 1.0; float wA = lob*d2 - 1.0;\n"
            + "  wB *= wB; wA *= wA; wB = (25.0/16.0)*wB - (25.0/16.0 - 1.0);\n"
            + "  float w = wB*wA;\n"
            + "  aC += c*w; aW += w;\n"
            + "}\n"
            + "void main() {\n"
            + "  vec2 pp = vTexCoord * uSrcSize.zw - vec2(0.5);\n"
            + "  vec2 fp = floor(pp); pp -= fp;\n"
            + "  vec2 pt = uSrcSize.xy;\n"
            + "  vec3 c_b = texture2D(uInputTex, (fp + vec2( 0.5,-0.5))*pt).rgb;\n"
            + "  vec3 c_c = texture2D(uInputTex, (fp + vec2( 1.5,-0.5))*pt).rgb;\n"
            + "  vec3 c_e = texture2D(uInputTex, (fp + vec2(-0.5, 0.5))*pt).rgb;\n"
            + "  vec3 c_f = texture2D(uInputTex, (fp + vec2( 0.5, 0.5))*pt).rgb;\n"
            + "  vec3 c_g = texture2D(uInputTex, (fp + vec2( 1.5, 0.5))*pt).rgb;\n"
            + "  vec3 c_h = texture2D(uInputTex, (fp + vec2( 2.5, 0.5))*pt).rgb;\n"
            + "  vec3 c_i = texture2D(uInputTex, (fp + vec2(-0.5, 1.5))*pt).rgb;\n"
            + "  vec3 c_j = texture2D(uInputTex, (fp + vec2( 0.5, 1.5))*pt).rgb;\n"
            + "  vec3 c_k = texture2D(uInputTex, (fp + vec2( 1.5, 1.5))*pt).rgb;\n"
            + "  vec3 c_l = texture2D(uInputTex, (fp + vec2( 2.5, 1.5))*pt).rgb;\n"
            + "  vec3 c_n = texture2D(uInputTex, (fp + vec2( 0.5, 2.5))*pt).rgb;\n"
            + "  vec3 c_o = texture2D(uInputTex, (fp + vec2( 1.5, 2.5))*pt).rgb;\n"
            + "  float bL=getLuma(c_b), cL=getLuma(c_c);\n"
            + "  float eL=getLuma(c_e), fL=getLuma(c_f), gL=getLuma(c_g), hL=getLuma(c_h);\n"
            + "  float iL=getLuma(c_i), jL=getLuma(c_j), kL=getLuma(c_k), lL=getLuma(c_l);\n"
            + "  float nL=getLuma(c_n), oL=getLuma(c_o);\n"
            + "  vec4 w = vec4((1.0-pp.x)*(1.0-pp.y), pp.x*(1.0-pp.y), (1.0-pp.x)*pp.y, pp.x*pp.y);\n"
            + "  float lA = dot(w, vec4(bL,cL,fL,gL));\n"
            + "  float lB = dot(w, vec4(eL,fL,iL,jL));\n"
            + "  float lC = dot(w, vec4(fL,gL,jL,kL));\n"
            + "  float lD = dot(w, vec4(gL,hL,kL,lL));\n"
            + "  float lE = dot(w, vec4(jL,kL,nL,oL));\n"
            + "  float dc = lD - lC, cb = lC - lB;\n"
            + "  float lenX = clamp(abs(lD-lB)*APrxLoRcpF1(max(abs(dc),abs(cb))), 0.0, 1.0); lenX *= lenX;\n"
            + "  float ec = lE - lC, ca = lC - lA;\n"
            + "  float lenY = clamp(abs(lE-lA)*APrxLoRcpF1(max(abs(ec),abs(ca))), 0.0, 1.0); lenY *= lenY;\n"
            + "  vec2 dir = vec2(lD-lB, lE-lA);\n"
            + "  float len = (lenX + lenY)*0.5; len *= len;\n"
            + "  float dirR = dot(dir,dir);\n"
            + "  if (dirR < (1.0/64.0)) { vec3 bi = c_f*w.x + c_g*w.y + c_j*w.z + c_k*w.w; gl_FragColor = vec4(bi,1.0); return; }\n"
            + "  dir *= APrxLoRsqF1(dirR);\n"
            + "  float stretch = (dir.x*dir.x + dir.y*dir.y)*APrxLoRcpF1(max(abs(dir.x),abs(dir.y)));\n"
            + "  vec2 len2 = vec2(1.0 + (stretch-1.0)*len, 1.0 - 0.5*len);\n"
            + "  float lob = 0.5 + ((0.25-0.04)-0.5)*len;\n"
            + "  float clp = APrxLoRcpF1(lob);\n"
            + "  vec3 aC = vec3(0.0); float aW = 0.0;\n"
            + "  FsrEasuTap(aC,aW, vec2( 0.0,-1.0)-pp, dir, len2, lob, clp, c_b);\n"
            + "  FsrEasuTap(aC,aW, vec2( 1.0,-1.0)-pp, dir, len2, lob, clp, c_c);\n"
            + "  FsrEasuTap(aC,aW, vec2(-1.0, 1.0)-pp, dir, len2, lob, clp, c_i);\n"
            + "  FsrEasuTap(aC,aW, vec2( 0.0, 1.0)-pp, dir, len2, lob, clp, c_j);\n"
            + "  FsrEasuTap(aC,aW, vec2( 0.0, 0.0)-pp, dir, len2, lob, clp, c_f);\n"
            + "  FsrEasuTap(aC,aW, vec2(-1.0, 0.0)-pp, dir, len2, lob, clp, c_e);\n"
            + "  FsrEasuTap(aC,aW, vec2( 1.0, 1.0)-pp, dir, len2, lob, clp, c_k);\n"
            + "  FsrEasuTap(aC,aW, vec2( 2.0, 1.0)-pp, dir, len2, lob, clp, c_l);\n"
            + "  FsrEasuTap(aC,aW, vec2( 2.0, 0.0)-pp, dir, len2, lob, clp, c_h);\n"
            + "  FsrEasuTap(aC,aW, vec2( 1.0, 0.0)-pp, dir, len2, lob, clp, c_g);\n"
            + "  FsrEasuTap(aC,aW, vec2( 1.0, 2.0)-pp, dir, len2, lob, clp, c_o);\n"
            + "  FsrEasuTap(aC,aW, vec2( 0.0, 2.0)-pp, dir, len2, lob, clp, c_n);\n"
            + "  vec3 minC = min(min(c_f,c_g), min(c_j,c_k));\n"
            + "  vec3 maxC = max(max(c_f,c_g), max(c_j,c_k));\n"
            + "  vec3 res = clamp(aC/aW, minC, maxC);\n"
            + "  gl_FragColor = vec4(res, 1.0);\n"
            + "}\n";

    /** SR2 Pass2：FSR RCAS（文档 §3.1 原样）。 */
    public static final String FSR_RCAS = HEADER
            + "uniform sampler2D uEasuTex;\n"
            + "uniform vec2 uInvDstSize;\n"
            + "uniform float uSharpnessStop;\n"
            + "#define FSR_RCAS_LIMIT (0.25 - (1.0/16.0))\n"
            + "void main() {\n"
            + "  vec3 b = texture2D(uEasuTex, vTexCoord + vec2(0.0,-uInvDstSize.y)).rgb;\n"
            + "  vec3 d = texture2D(uEasuTex, vTexCoord + vec2(-uInvDstSize.x,0.0)).rgb;\n"
            + "  vec3 e = texture2D(uEasuTex, vTexCoord).rgb;\n"
            + "  vec3 f = texture2D(uEasuTex, vTexCoord + vec2(uInvDstSize.x,0.0)).rgb;\n"
            + "  vec3 h = texture2D(uEasuTex, vTexCoord + vec2(0.0,uInvDstSize.y)).rgb;\n"
            + "  float bL = b.g + 0.5*(b.r + b.b);\n"
            + "  float dL = d.g + 0.5*(d.r + d.b);\n"
            + "  float eL = e.g + 0.5*(e.r + e.b);\n"
            + "  float fL = f.g + 0.5*(f.r + f.b);\n"
            + "  float hL = h.g + 0.5*(h.r + h.b);\n"
            + "  float nz = 0.25*(bL + dL + fL + hL) - eL;\n"
            + "  float rangeL = max(max(max(bL,dL),max(eL,fL)),hL) - min(min(min(bL,dL),min(eL,fL)),hL);\n"
            + "  nz = clamp(abs(nz)/max(rangeL,1e-4), 0.0, 1.0);\n"
            + "  nz = 1.0 - 0.5*nz;\n"
            + "  vec3 mn4 = min(min(b,d), min(f,h));\n"
            + "  vec3 mx4 = max(max(b,d), max(f,h));\n"
            + "  vec3 hitMin = min(mn4, e) / max(4.0*mx4, vec3(1e-4));\n"
            + "  vec3 hitMax = (1.0 - max(mx4, e)) / max(4.0*mn4 - 4.0, vec3(-4.0));\n"
            + "  vec3 lobeRGB = max(-hitMin, hitMax);\n"
            + "  float lobe = max(-FSR_RCAS_LIMIT, min(max(lobeRGB.r, max(lobeRGB.g, lobeRGB.b)), 0.0)) * exp2(-clamp(uSharpnessStop,0.0,2.0)) * nz;\n"
            + "  vec3 res = (lobe*(b + d + f + h) + e) / (4.0*lobe + 1.0);\n"
            + "  gl_FragColor = vec4(clamp(res,0.0,1.0), 1.0);\n"
            + "}\n";
}
